import { describe, expect, it } from 'vitest';
import moduleNodesJson from '../module-1/nodes.json';
import rootNodesJson from '../nodes.json';
import draftNodesJson from '../draft-nodes.json';
import moduleEdgesJson from '../module-1/edges.json';
import rootEdgesJson from '../edges.json';
import moduleStandardEdgesJson from '../module-1/standard-edges.json';
import rootStandardEdgesJson from '../standard-edges.json';

const TARGET_NODE_ID = 'math.im3.skill.1.2.estimate-roots-by-graphing';
const EXAMPLE_TWO_ATOMIC_NODE_ID =
  'math.im3.skill.1.2.find-two-numbers-with-given-sum-and-product-by-graphing';

const EXPECTED_NODE = {
  id: TARGET_NODE_ID,
  kind: 'skill',
  title: 'Estimate roots of a quadratic equation by graphing',
  domain: 'math.im3',
  description:
    'Estimate roots of a quadratic equation by graphing and state the consecutive integers that bound each root.',
  sourceRefs: [
    'apps/integrated-math-3/curriculum/module-1-class-period-plan.md (1-2, Example 3)',
    'apps/integrated-math-3/curriculum/IM3-reveal-module-1.pdf#page=15',
  ],
  reviewStatus: 'draft',
  metadata: { course: 'im3', module: '1', lesson: '2' },
  rendererKey: 'graphing-explorer',
  independentPracticeReady: false,
};
const ESTIMATE_ROOTS_GENERATOR_NODE_ID =
  'math.im3.generator.m1.estimate-roots-by-graphing';
const TWO_REAL_SOLUTIONS_GENERATOR_NODE_ID =
  'math.im3.generator.m1.two-real-solutions-graphing';
const EXPECTED_GENERATOR_NODE = {
  id: ESTIMATE_ROOTS_GENERATOR_NODE_ID,
  kind: 'generator',
  title: 'Estimate Roots by Graphing Generator',
  domain: 'math.im3',
  sourceRefs: [{ source: 'pilot', note: 'Module 1 pilot generator' }],
  derived: true,
  derivationMethod: 'registered-generator',
  reviewStatus: 'draft',
  metadata: {
    course: 'im3',
    module: '1',
    generatorKey: 'estimate-roots-by-graphing',
  },
};
const EXPECTED_CONTAINS_EDGE = {
  id: 'math.im3.edge.m1.162',
  type: 'contains',
  sourceId: 'math.im3.lesson.1.2',
  targetId: TARGET_NODE_ID,
  weight: 1,
  confidence: 'high',
  reviewStatus: 'draft',
  metadata: { course: 'im3', module: '1' },
  rationale: 'Skill contained in Lesson 1.2',
  sourceRefs: [
    'apps/integrated-math-3/curriculum/module-1-class-period-plan.md (1-2, Example 3)',
    'apps/integrated-math-3/curriculum/IM3-reveal-module-1.pdf#page=15',
  ],
};
const EXPECTED_ALIGNMENT_EDGE = {
  id: 'math.alignment.im3-skill-1-2-estimate-roots-by-graphing-to-ccss-hsa-rei-b-4',
  type: 'aligned_to_standard',
  sourceId: TARGET_NODE_ID,
  targetId: 'math.standard.ccss.hsa-rei-b-4',
  weight: 0.8,
  confidence: 'high',
  sourceRefs: [
    {
      source: 'apps/integrated-math-3/curriculum/IM3-reveal-module-1.pdf#page=15',
      note: 'Primary alignment for authored Example 3',
    },
  ],
  reviewStatus: 'draft',
  rationale: 'Primary alignment for the authored Example 3 root-estimation-by-graphing capability',
  metadata: { isPrimary: true, course: 'im3' },
};
const EXPECTED_GENERATED_BY_EDGE = {
  id: 'math.im3.edge.m1.163',
  type: 'generated_by',
  sourceId: TARGET_NODE_ID,
  targetId: ESTIMATE_ROOTS_GENERATOR_NODE_ID,
  weight: 1,
  confidence: 'high',
  reviewStatus: 'draft',
  metadata: { course: 'im3', module: '1' },
  rationale: `Skill ${TARGET_NODE_ID} generated by ${ESTIMATE_ROOTS_GENERATOR_NODE_ID}`,
  sourceRefs: [{ source: 'pilot', note: 'Module 1 pilot generator' }],
  derived: true,
  derivationMethod: 'generator-registry-mapping',
};

describe('Lesson 1.2 Example 3 atomic node', () => {
  it('defines the exact Example 3 graphing skill in all node mirrors', () => {
    const catalogs = [
      moduleNodesJson.nodes,
      rootNodesJson.nodes,
      draftNodesJson.nodes,
      rootEdgesJson.nodes,
      rootStandardEdgesJson.nodes,
    ];

    const targetNodes = catalogs.map((nodes) => {
      expect(nodes.filter((node) => node.id === TARGET_NODE_ID)).toEqual([
        EXPECTED_NODE,
      ]);

      const targetIndex = nodes.findIndex((node) => node.id === TARGET_NODE_ID);
      const exampleTwoIndex = nodes.findIndex(
        (node) => node.id === EXAMPLE_TWO_ATOMIC_NODE_ID,
      );
      expect(targetIndex).toBe(exampleTwoIndex + 1);

      return nodes[targetIndex];
    });

    expect(targetNodes[1]).toEqual(targetNodes[0]);
    expect(targetNodes[2]).toEqual(targetNodes[0]);
    expect(targetNodes[3]).toEqual(targetNodes[0]);
    expect(targetNodes[4]).toEqual(targetNodes[0]);
  });

  it('defines the exact Example 3 generator node in its owner mirrors', () => {
    const ownerCatalogs = [
      moduleNodesJson.nodes,
      rootNodesJson.nodes,
      rootEdgesJson.nodes,
    ];
    const targetNodes = ownerCatalogs.map((nodes) => {
      expect(nodes.filter((node) => node.id === ESTIMATE_ROOTS_GENERATOR_NODE_ID)).toEqual([
        EXPECTED_GENERATOR_NODE,
      ]);

      const targetIndex = nodes.findIndex(
        (node) => node.id === ESTIMATE_ROOTS_GENERATOR_NODE_ID,
      );
      expect(nodes[targetIndex - 1]?.id).toBe(TWO_REAL_SOLUTIONS_GENERATOR_NODE_ID);
      return nodes[targetIndex];
    });

    expect(targetNodes[1]).toEqual(targetNodes[0]);
    expect(targetNodes[2]).toEqual(targetNodes[0]);

    const nonOwnerCatalogs = [
      draftNodesJson.nodes,
      moduleStandardEdgesJson.nodes,
      rootStandardEdgesJson.nodes,
    ];
    for (const nodes of nonOwnerCatalogs) {
      expect(nodes.filter((node) => node.id === ESTIMATE_ROOTS_GENERATOR_NODE_ID)).toHaveLength(0);
    }
  });

  it('defines the exact Example 3 generated-by edge in both edge catalogs', () => {
    const catalogs = [moduleEdgesJson.edges, rootEdgesJson.edges];
    const targetEdges = catalogs.map((edges) => {
      expect(edges.filter((edge) => edge.id === EXPECTED_GENERATED_BY_EDGE.id)).toEqual([
        EXPECTED_GENERATED_BY_EDGE,
      ]);

      const targetIndex = edges.findIndex(
        (edge) => edge.id === EXPECTED_GENERATED_BY_EDGE.id,
      );
      const previousEdge = edges[targetIndex - 1];
      expect(previousEdge?.id).toBe('math.im3.edge.m1.162');
      return edges[targetIndex];
    });

    expect(targetEdges[1]).toEqual(targetEdges[0]);

    for (const edges of [moduleStandardEdgesJson.edges, rootStandardEdgesJson.edges]) {
      expect(edges.filter((edge) => edge.id === EXPECTED_GENERATED_BY_EDGE.id)).toHaveLength(0);
    }
  });

  it('contains the exact Example 3 skill in both Lesson 1.2 edge catalogs', () => {
    const catalogs = [moduleEdgesJson.edges, rootEdgesJson.edges];
    const targetEdges = catalogs.map((edges) => {
      expect(edges.filter((edge) => edge.id === EXPECTED_CONTAINS_EDGE.id)).toEqual([
        EXPECTED_CONTAINS_EDGE,
      ]);
      expect(
        edges.filter(
          (edge) =>
            edge.type === 'supports' &&
            edge.sourceId === 'math.im3.example.1.2.009' &&
            edge.targetId === TARGET_NODE_ID,
        ),
      ).toHaveLength(0);
      return edges.find((edge) => edge.id === EXPECTED_CONTAINS_EDGE.id);
    });

    expect(targetEdges[1]).toEqual(targetEdges[0]);
  });

  it('defines the exact Example 3 skill standard alignment in all edge mirrors', () => {
    const catalogs = [
      rootEdgesJson.edges,
      moduleStandardEdgesJson.edges,
      rootStandardEdgesJson.edges,
    ];
    const targetEdges = catalogs.map((edges) => {
      const matches = edges.filter((edge) => edge.id === EXPECTED_ALIGNMENT_EDGE.id);
      expect(matches).toEqual([EXPECTED_ALIGNMENT_EDGE]);
      return matches[0];
    });

    expect(targetEdges[1]).toEqual(targetEdges[0]);
    expect(targetEdges[2]).toEqual(targetEdges[0]);
  });
});
