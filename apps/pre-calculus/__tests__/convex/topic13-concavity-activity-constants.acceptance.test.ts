describe("Topic 1.3 concavity activity constants", () => {
  it("defines exact identity and grading constants with enabled evidence", () => {
    expect(PRECALCULUS_TOPIC_13_CONCAVITY_NODE_ID).toBe(
      "math.precalc.skill.1.3.determine-concavity-from-rate-of-change",
    );
    const activityIds = [
      PRECALCULUS_TOPIC_13_CONCAVITY_WORKED_ACTIVITY_ID,
      PRECALCULUS_TOPIC_13_CONCAVITY_GUIDED_ACTIVITY_ID,
      PRECALCULUS_TOPIC_13_CONCAVITY_INDEPENDENT_ACTIVITY_ID,
    ];
    expect(activityIds).toEqual([
      `${PRECALCULUS_TOPIC_13_CONCAVITY_NODE_ID}.worked_example`,
      `${PRECALCULUS_TOPIC_13_CONCAVITY_NODE_ID}.guided_practice`,
      `${PRECALCULUS_TOPIC_13_CONCAVITY_NODE_ID}.independent_practice`,
    ]);
    expect(new Set(activityIds).size).toBe(3);
    expect(new Set([...EXISTING_ACTIVITY_IDS, ...activityIds]).size).toBe(
      EXISTING_ACTIVITY_IDS.length + activityIds.length,
    );
    expect(PRECALCULUS_LEARNING_EVIDENCE_PILOT_NODE_IDS).toContain(
      PRECALCULUS_TOPIC_13_CONCAVITY_NODE_ID,
    );

    expect(PRECALCULUS_TOPIC_13_CONCAVITY_COMPONENT_KEY).toBe("concavity-from-rate-change");
    expect(PRECALCULUS_TOPIC_13_CONCAVITY_GENERATOR_KEY).toBe("topic13-concavity-from-rate-change");
    expect(PRECALCULUS_TOPIC_13_CONCAVITY_WORKED_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_13_CONCAVITY_GENERATOR_KEY,
      variantSeed: 0,
    });
    expect(PRECALCULUS_TOPIC_13_CONCAVITY_GUIDED_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_13_CONCAVITY_GENERATOR_KEY,
      variantSeed: 1,
    });
    expect(PRECALCULUS_TOPIC_13_CONCAVITY_INDEPENDENT_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_13_CONCAVITY_GENERATOR_KEY,
      variantSeed: 2,
    });

    const generator = getGenerator(PRECALCULUS_TOPIC_13_CONCAVITY_GENERATOR_KEY);
    expect(generator.key).toBe(PRECALCULUS_TOPIC_13_CONCAVITY_GENERATOR_KEY);
    expect(generator.nodeIds).toEqual([PRECALCULUS_TOPIC_13_CONCAVITY_NODE_ID]);
  });
});
