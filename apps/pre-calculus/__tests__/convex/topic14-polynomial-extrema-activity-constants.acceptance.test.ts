describe("Topic 1.4 polynomial extrema activity constants", () => {
  it("defines exact identity, projections, configs, and enabled evidence", () => {
    expect(PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_NODE_ID).toBe(
      "math.precalc.skill.1.4.identify-relative-and-absolute-extrema-from-graphs",
    );
    expect(EXTREMA_ACTIVITY_IDS).toEqual([
      `${PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_NODE_ID}.worked_example`,
      `${PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_NODE_ID}.guided_practice`,
      `${PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_NODE_ID}.independent_practice`,
    ]);
    expect(new Set(EXTREMA_ACTIVITY_IDS).size).toBe(3);
    expect(new Set([...EXISTING_ACTIVITY_IDS, ...EXTREMA_ACTIVITY_IDS]).size).toBe(
      EXISTING_ACTIVITY_IDS.length + EXTREMA_ACTIVITY_IDS.length,
    );

    const projection = JSON.parse(fs.readFileSync(AP_PROJECTION_PATH, "utf8")) as {
      activities: Array<{ nodeId: string; stableActivityId: string; mode: string }>;
    };
    const projectedActivities = projection.activities.filter(
      (activity) => activity.nodeId === PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_NODE_ID,
    );
    expect(projectedActivities).toHaveLength(3);
    expect(projectedActivities.map((activity) => activity.stableActivityId)).toEqual(
      EXTREMA_ACTIVITY_IDS,
    );
    expect(projectedActivities.map((activity) => activity.mode)).toEqual([
      "worked_example",
      "guided_practice",
      "independent_practice",
    ]);

    expect(PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_COMPONENT_KEY).toBe(
      "polynomial-extrema-from-graph",
    );
    expect(PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GENERATOR_KEY).toBe(
      "topic14-polynomial-extrema-from-graph",
    );
    expect(PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_WORKED_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GENERATOR_KEY,
      variantSeed: 0,
    });
    expect(PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GUIDED_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GENERATOR_KEY,
      variantSeed: 1,
    });
    expect(PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_INDEPENDENT_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GENERATOR_KEY,
      variantSeed: 2,
    });

    expect(PRECALCULUS_LEARNING_EVIDENCE_PILOT_NODE_IDS).toContain(
      PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_NODE_ID,
    );
    expect(
      PRECALCULUS_LEARNING_EVIDENCE_PILOT_NODE_IDS.filter(
        (nodeId) => nodeId === PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_NODE_ID,
      ),
    ).toHaveLength(1);
    expect(new Set(PRECALCULUS_LEARNING_EVIDENCE_PILOT_NODE_IDS).size).toBe(
      PRECALCULUS_LEARNING_EVIDENCE_PILOT_NODE_IDS.length,
    );

    const generator = getGenerator(PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GENERATOR_KEY);
    expect(generator.key).toBe(PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GENERATOR_KEY);
    expect(generator.nodeIds).toEqual([PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_NODE_ID]);
  });

  it("connects the accepted extrema runtime paths", () => {
    const activitiesSource = fs.readFileSync(
      path.resolve(process.cwd(), "convex/activities.ts"),
      "utf8",
    );
    const evidenceSource = fs.readFileSync(
      path.resolve(process.cwd(), "convex/learningEvidence.ts"),
      "utf8",
    );
    const seedSource = fs.readFileSync(
      path.resolve(process.cwd(), "convex/seed/seed_lesson_1_4.ts"),
      "utf8",
    );

    expect(activitiesSource).toContain("createTopic14PolynomialExtremaFromGraphSubmission");
    expect(activitiesSource).toContain("createTopic14PolynomialExtremaWorkedSubmission");
    expect(evidenceSource).toContain("PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GUIDED_ACTIVITY_ID");
    expect(evidenceSource).toContain(
      "PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_INDEPENDENT_ACTIVITY_ID",
    );
    expect(evidenceSource).toContain("submitTopic14PolynomialExtremaWorkedSubmission");
    expect(evidenceSource).toContain("getPrecalculusTopic14PolynomialExtremaKnowledgeState");
    expect(seedSource).toContain("PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_WORKED_ACTIVITY_ID");
    expect(seedSource).toContain("PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_GUIDED_ACTIVITY_ID");
    expect(seedSource).toContain("PRECALCULUS_TOPIC_14_POLYNOMIAL_EXTREMA_INDEPENDENT_ACTIVITY_ID");
  });
});
