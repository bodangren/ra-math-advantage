import { describe, expect, it } from 'vitest';

import { getGenerator } from '@math-platform/math-content/knowledge-space';
import {
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_COMPONENT_KEY,
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GENERATOR_KEY,
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GUIDED_GRADING_CONFIG,
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_INDEPENDENT_GRADING_CONFIG,
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_WORKED_GRADING_CONFIG,
} from '@/convex/activities';
import {
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GUIDED_ACTIVITY_ID,
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_INDEPENDENT_ACTIVITY_ID,
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_NODE_ID,
  PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_WORKED_ACTIVITY_ID,
} from '@/lib/learning-evidence/precalc-pilot';

describe('Topic 1.2 pointwise least-rate activity constants', () => {
  it('defines stable mode IDs, exact configs, and the shared generator identity', () => {
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_NODE_ID).toBe(
      'math.precalc.skill.1.2.identify-least-pointwise-rate-of-change-from-graphs',
    );
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_WORKED_ACTIVITY_ID).toBe(
      `${PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_NODE_ID}.worked_example`,
    );
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GUIDED_ACTIVITY_ID).toBe(
      `${PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_NODE_ID}.guided_practice`,
    );
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_INDEPENDENT_ACTIVITY_ID).toBe(
      `${PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_NODE_ID}.independent_practice`,
    );
    expect(new Set([
      PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_WORKED_ACTIVITY_ID,
      PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GUIDED_ACTIVITY_ID,
      PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_INDEPENDENT_ACTIVITY_ID,
    ]).size).toBe(3);
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_COMPONENT_KEY).toBe('pointwise-least-rate-choice');
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GENERATOR_KEY).toBe('topic12-pointwise-least-rate-choice');
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_WORKED_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GENERATOR_KEY,
      variantSeed: 0,
    });
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GUIDED_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GENERATOR_KEY,
      variantSeed: 1,
    });
    expect(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_INDEPENDENT_GRADING_CONFIG).toEqual({
      generatorKey: PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GENERATOR_KEY,
      variantSeed: 2,
    });

    const generator = getGenerator(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GENERATOR_KEY);
    expect(generator.key).toBe(PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_GENERATOR_KEY);
    expect(generator.nodeIds).toEqual([
      PRECALCULUS_TOPIC_12_POINTWISE_LEAST_RATE_NODE_ID,
    ]);
  });
});
