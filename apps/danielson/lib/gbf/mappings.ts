const skill = (id: string) => `danielson.tlac.skill.${id}`;

function mapping(
  actionStepId: string,
  techniqueId: string,
  role: GbfMapping["role"],
  classification: GbfMapping["classification"],
  rationale: string,
): GbfMapping {
  return {
    actionStepId,
    skillId: skill(techniqueId),
    role,
    classification,
    rationale,
  };
}

