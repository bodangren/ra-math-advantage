import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
import { parseEnv } from 'node:util';
const env = parseEnv(readFileSync('apps/danielson/.env.local', 'utf8'));
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage();
await page.goto('http://localhost:3014/auth/login');
await page.waitForLoadState('networkidle');
console.log(await page.locator('main').innerText());
await page.getByLabel('Username').fill('demo.head');
await page.getByLabel('Password', { exact: true }).fill(env.DANIELSON_DEMO_PASSWORD);
await page.getByRole('button', { name: 'Sign in' }).click();
await page.waitForURL('http://localhost:3014/');
await page.goto('http://localhost:3014/reports');
await page.waitForLoadState('networkidle');
console.log(await page.locator('main').innerText());
console.log(await page.locator('main a').evaluateAll(nodes => nodes.map(n => ({ text: n.textContent, href: n.getAttribute('href') }))));
await page.screenshot({ path: 'tmp/danielson-admin-growth/portfolio.png', fullPage: true });
await browser.close();
